#!/usr/bin/env node
/**
 * Imports the film catalog from the local Videothek page into the repo.
 *
 *   node scripts/videothek/import-catalog.mjs [path/to/_videothek/index.html]
 *
 * Writes src/data/videothek/catalog.json (texts, ratings, songs, characters).
 * Local file paths (the "files" lists) are dropped on purpose.
 * The catalog is NOT a release list: nothing in it is public until
 * src/data/videothek/releases.json pins it (see release.mjs).
 */
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import vm from 'node:vm';

const src = process.argv[2] || path.join(os.homedir(), 'Movies/seez/_videothek/index.html');
const out = path.resolve('src/data/videothek/catalog.json');
const html = fs.readFileSync(src, 'utf8');

/** Evaluates the literal assigned to `const NAME = …` (object or array). */
function grab(name) {
  const start = html.indexOf(`const ${name} =`);
  if (start < 0) throw new Error(`const ${name} not found in ${src}`);
  let i = html.indexOf('=', start) + 1;
  while (/\s/.test(html[i])) i++;
  const open = html[i];
  const close = open === '{' ? '}' : ']';
  let depth = 0;
  let str = null;
  for (let j = i; j < html.length; j++) {
    const c = html[j];
    if (str) {
      if (c === '\\') j++;
      else if (c === str) str = null;
      continue;
    }
    if (c === '"' || c === "'" || c === '`') str = c;
    else if (c === open) depth++;
    else if (c === close && --depth === 0) return vm.runInNewContext(`(${html.slice(i, j + 1)})`, { H: '', SK: '' });
  }
  throw new Error(`unterminated literal for ${name}`);
}

const V = grab('V');
const R = grab('R');
const SONGS = grab('SONGS');
const CH = grab('CH');
const posterN = grab('posterN');

const songOf = {};
for (const s of SONGS) for (const id of s.videos) songOf[id] = s;

const films = Object.entries(V).map(([id, v]) => {
  const r = R[id];
  const song = songOf[id];
  const [title, subtitle = ''] = String(v.t).split(' · ');
  return {
    id,
    title,
    subtitle,
    characters: v.ch || [],
    date: v.date || '',
    length: v.len || '',
    resolution: v.res || '',
    workStatus: (v.status && v.status[0]) || 'draft',
    workNote: (v.status && v.status[1]) || '',
    how: v.how || '',
    tags: v.tags || [],
    used: v.used || [],
    made: v.gen || [],
    thumbs: v.n || 5,
    poster: posterN[id] || 1,
    rating: r ? { g: r.g, w: r.w, c: r.c, l: r.l, s: r.s, why: r.why || '' } : null,
    song: song ? { key: song.key, title: song.title, meta: song.meta || '', note: song.note || '' } : null,
  };
});

const characters = Object.fromEntries(Object.entries(CH).map(([k, c]) => [k, { name: c.name }]));

const catalog = {
  $comment:
    'Generated by scripts/videothek/import-catalog.mjs from the local Videothek. Texts only, no media. Public visibility is decided by releases.json alone.',
  importedAt: new Date().toISOString().slice(0, 10),
  characters,
  films,
};

// Strip local paths from free text, e.g. "Overlays (~/Downloads/x/)" -> "Overlays".
const scrub = (s) => s.replace(/\s*\((?:~\/|\/Users\/)[^)]*\)/g, '').replace(/(?:~\/|\/Users\/)\S+/g, '[lokal]');
const json = JSON.stringify(catalog, (_key, v) => (typeof v === 'string' ? scrub(v) : v), 2) + '\n';
const leaks = json.split('\n').filter((l) => /\/Users\/|~\/|Application Support/.test(l));
if (leaks.length) throw new Error('local path leaked into catalog:\n' + leaks.join('\n'));
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, json);
console.log(`catalog: ${films.length} films, ${SONGS.length} songs -> ${path.relative(process.cwd(), out)}`);
